
USE DATABASE INCUBYTE_DB;
USE SCHEMA PUBLIC;

-- Master Members Table
CREATE TABLE IF NOT EXISTS MEMBERS (
    MEMBER_NAME VARCHAR(255) NOT NULL PRIMARY KEY,
    MEMBER_ID VARCHAR(18) NOT NULL,
    ENROLLMENT_DATE DATE NOT NULL,
    LAST_FLIGHT_DATE DATE,
    TIER_CODE VARCHAR(20),
    AGENT_NAME VARCHAR(100),
    STATE VARCHAR(50),
    COUNTRY VARCHAR(50),
    DOB DATE,
    IS_ACTIVE VARCHAR(1),
    AGE INTEGER,
    STALE_MEMBER VARCHAR(5)
);

-- Redemption Transactions Table
CREATE TABLE IF NOT EXISTS REDEMPTIONS (
    TXN_ID VARCHAR(50) PRIMARY KEY,
    TXN_DATE DATE,
    PARTNER VARCHAR(100),
    MILES_REDEEMED NUMBER(12,0),
    STATUS VARCHAR(30),
    MEMBER_ID VARCHAR(18),
    FEED_DATE DATE
);
